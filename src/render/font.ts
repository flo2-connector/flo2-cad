/** Draws upper-cased text into an RGB buffer at (x, y), each font pixel `s` × `s`. Returns the width drawn. */
export function drawText(rgb: Uint8Array, width: number, height: number, x: number, y: number, text: string, s: number, color: readonly [number, number, number]): number {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = G[ch];
    if (g) {
      const bits = g.padEnd(35, '.');
      for (let row = 0; row < 7; row++)
        for (let col = 0; col < 5; col++) {
          if (bits[row * 5 + col] !== '#') continue;
          for (let dy = 0; dy < s; dy++)
            for (let dx = 0; dx < s; dx++) {
              const px = cx + col * s + dx, py = y + row * s + dy;
              if (px >= 0 && py >= 0 && px < width && py < height) rgb.set(color, (py * width + px) * 3);
            }
        }
    }
    cx += 6 * s;
  }
  return cx - x;
}

export const textWidth = (text: string, s: number) => text.length * 6 * s;

/** Breaks text into lines that fit `maxChars`. */
export function wrap(text: string, maxChars: number): string[] {
  const out: string[] = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (!word) continue;
    if ((line ? line.length + 1 : 0) + word.length > maxChars && line) {
      out.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  if (line) out.push(line);
  return out;
}
